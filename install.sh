# ── Detect OS ─────────────────────────────────────────────────────────────────
detect_os() {
  case "$(uname -s)" in
    Darwin) echo "macos" ;;
    Linux)
      if grep -qi microsoft /proc/version 2>/dev/null; then
        echo "wsl"
      else
        echo "linux"
      fi
      ;;
    *) error "Unsupported OS: $(uname -s). Bookmark supports macOS, Linux, and WSL2." ;;
  esac
}

OS=$(detect_os)
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV_DIR="$REPO_ROOT/.venv"
CLI_TARGET="/usr/local/bin/bookmark"

info "Detected OS: ${BOLD}$OS${RESET}"
info "Install root: ${BOLD}$REPO_ROOT${RESET}"

# ── Dependency checks ─────────────────────────────────────────────────────────
step "Checking dependencies"

require_cmd() {
  if ! command -v "$1" &>/dev/null; then
    error "'$1' is required but not found. $2"
  fi
  success "$1 found ($(command -v "$1"))"
}

require_cmd python3    "Install Python 3.10+ from https://python.org"
require_cmd pip3       "Comes with Python — reinstall Python if missing"
require_cmd node       "Install Node.js 18+ from https://nodejs.org"
require_cmd npm        "Comes with Node.js"
require_cmd psql       "Install PostgreSQL: https://www.postgresql.org/download/"
require_cmd pg_isready "Part of the PostgreSQL client tools"

# Python version check
PY_VER=$(python3 -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')")
PY_MAJOR=$(echo "$PY_VER" | cut -d. -f1)
PY_MINOR=$(echo "$PY_VER" | cut -d. -f2)
if [[ "$PY_MAJOR" -lt 3 || ("$PY_MAJOR" -eq 3 && "$PY_MINOR" -lt 10) ]]; then
  error "Python 3.10+ required, found $PY_VER"
fi
success "Python $PY_VER"

# Node version check
NODE_VER=$(node --version | sed 's/v//')
NODE_MAJOR=$(echo "$NODE_VER" | cut -d. -f1)
if [[ "$NODE_MAJOR" -lt 18 ]]; then
  error "Node.js 18+ required, found $NODE_VER"
fi
success "Node.js $NODE_VER"

# ── Ollama ────────────────────────────────────────────────────────────────────
step "Setting up Ollama"

install_ollama() {
  info "Installing Ollama..."
  if [[ "$OS" == "macos" ]]; then
    if command -v brew &>/dev/null; then
      brew install ollama
    else
      curl -fsSL https://ollama.com/install.sh | sh
    fi
  else
    curl -fsSL https://ollama.com/install.sh | sh
  fi
}

if ! command -v ollama &>/dev/null; then
  warn "Ollama not found — installing automatically"
  install_ollama
else
  success "Ollama found ($(ollama --version 2>/dev/null || echo 'installed'))"
fi

# ── Environment file ──────────────────────────────────────────────────────────
step "Creating environment configuration"

ENV_FILE="$REPO_ROOT/.env"

if [[ -f "$ENV_FILE" ]]; then
  warn ".env already exists — skipping (delete it to reconfigure)"
else
  # Generate a random Django secret key
  SECRET_KEY=$(python3 -c "import secrets, string; \
    chars = string.ascii_letters + string.digits + '!@#%^&*(-_=+)'; \
    print(''.join(secrets.choice(chars) for _ in range(50)))")

  cat > "$ENV_FILE" << EOF
# ── Bookmark Environment Configuration ──────────────────────────────────────
# Generated by install.sh on $(date)
# Edit this file to change your configuration.

# Django
DJANGO_SECRET_KEY=$SECRET_KEY
DJANGO_DEBUG=False
DJANGO_ALLOWED_HOSTS=127.0.0.1,localhost

# Database (PostgreSQL)
DB_NAME=bookmark
DB_USER=bookmark
DB_PASSWORD=bookmark_local
DB_HOST=localhost
DB_PORT=5432

# Ports
BOOKMARK_SERVER_PORT=8080
REACT_PORT=8081

# Ollama
OLLAMA_BASE_URL=http://localhost:11434

# Models — fixed for this version, do not change
EMBEDDING_MODEL=nomic-embed-text-v2-moe
GENERATION_MODEL=gemma4:e2b

# Dev mode (set to True to keep temp files for pipeline replay)
BOOKMARK_DEV_MODE=False
EOF
  success ".env created"
fi

# ── Python virtual environment ────────────────────────────────────────────────
step "Setting up Python virtual environment"

if [[ ! -d "$VENV_DIR" ]]; then
  python3 -m venv "$VENV_DIR"
  success "Virtual environment created at .venv/"
else
  success "Virtual environment already exists"
fi

# shellcheck disable=SC1091
source "$VENV_DIR/bin/activate"

"$VENV_DIR/bin/pip" install --upgrade pip --quiet
info "Installing Python dependencies into .venv/ (isolated, never touches system Python)..."
"$VENV_DIR/bin/pip" install -r "$REPO_ROOT/requirements.txt" --quiet
success "Python dependencies installed into .venv/"

# ── Node dependencies ─────────────────────────────────────────────────────────
step "Installing Node.js dependencies"

if [[ -f "$REPO_ROOT/frontend/package.json" ]]; then
  cd "$REPO_ROOT/frontend"
  npm install --silent
  PORT=8081 npm run build --silent
  cd "$REPO_ROOT"
  success "Frontend built (port 8081)"
else
  warn "No frontend/package.json found — skipping frontend build"
fi

if [[ -f "$REPO_ROOT/extension/package.json" ]]; then
  info "Building browser extension..."
  cd "$REPO_ROOT/extension"
  npm install --silent

  # Inject the local server port into the extension's config before building
  # The extension needs to know where to POST saved items
  if [[ -f "src/config.ts" ]]; then
    sed -i.bak "s|http://localhost:[0-9]*/|http://localhost:${BOOKMARK_SERVER_PORT:-8080}/|g" src/config.ts
    rm -f src/config.ts.bak
    info "Extension config patched with port ${BOOKMARK_SERVER_PORT:-8080}"
  elif [[ -f "src/config.js" ]]; then
    sed -i.bak "s|http://localhost:[0-9]*/|http://localhost:${BOOKMARK_SERVER_PORT:-8080}/|g" src/config.js
    rm -f src/config.js.bak
    info "Extension config patched with port ${BOOKMARK_SERVER_PORT:-8080}"
  fi

  npm run build --silent
  cd "$REPO_ROOT"

  EXTENSION_DIST="$REPO_ROOT/extension/dist"
  if [[ -d "$EXTENSION_DIST" ]]; then
    success "Browser extension built → $EXTENSION_DIST"
    # Write a small helper file Chrome users can reference
    cat > "$REPO_ROOT/LOAD_EXTENSION.txt" << EXTEOF
How to load the Bookmark browser extension in Chrome
─────────────────────────────────────────────────────
1. Open Chrome and go to:   chrome://extensions
2. Enable "Developer mode"  (toggle, top-right corner)
3. Click "Load unpacked"
4. Select this folder:      $EXTENSION_DIST
5. The Bookmark icon will appear in your Chrome toolbar.

To reload after an update:  run 'bookmark update', then click the
refresh icon on the extension card at chrome://extensions

Extension ID will be shown on the chrome://extensions page.
EXTEOF
    success "Extension load instructions written → LOAD_EXTENSION.txt"
  else
    warn "Build ran but dist/ folder not found — check extension/package.json build script"
  fi
else
  warn "No extension/package.json found — skipping extension build"
fi

# ── PostgreSQL setup ──────────────────────────────────────────────────────────
step "Configuring PostgreSQL"

# Source .env to get DB vars
set -o allexport
